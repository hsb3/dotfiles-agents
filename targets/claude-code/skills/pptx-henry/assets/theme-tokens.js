function validateTheme(themeKey, theme) {
  for (const token of REQUIRED_SEMANTIC_TOKENS) {
    if (!/^[0-9A-F]{6}$/.test(theme[token] || "")) {
      throw new Error(`Theme "${themeKey}" has an invalid or missing ${token} token`);
    }
  }
}

for (const [themeKey, theme] of Object.entries(THEMES)) {
  validateTheme(themeKey, theme);
}

module.exports = { REQUIRED_SEMANTIC_TOKENS, THEMES, validateTheme };

if (require.main === module) {
  const key = process.argv[2];
  if (!key) {
    for (const [k, t] of Object.entries(THEMES)) {
      console.log(`${k.padEnd(24)} ${t.name} — ${t.useFor}`);
    }
  } else if (THEMES[key]) {
    const t = THEMES[key];
    console.log(`${t.name} (${key})\n${t.useFor}\n`);
    for (const token of REQUIRED_SEMANTIC_TOKENS) {
      console.log(`${token.padEnd(16)} #${t[token]}`);
    }
  } else {
    console.error(`Unknown theme "${key}". Available: ${Object.keys(THEMES).join(", ")}`);
    process.exit(2);
  }
}
