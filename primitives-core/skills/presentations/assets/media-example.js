"use strict";
// Image placement and status icons, correct by construction. From the package root:
//   node deck-kit/media-example.js out.pptx
// - srcW/srcH (pixels) are required: pptxgenjs never measures a file and this package's
//   image-size is a stub, so a guessed size silently stretches or mis-crops the picture.
// - contain fits the whole image inside the box, uncropped. cover fills the box with a centred
//   crop; a crop or zoom names the exact source region it shows in its caption.
// - An interface screenshot shows the UI. It is not proof that a runtime integration works.
// - Keep proportions (never hand-set a picture's w/h) and keep the source line next to every image.
// The sources are test patterns generated below (grid, centred circle, four distinct corners),
// so a stretch or a wrong crop is visible at a glance. Matrix statuses are illustrative.
const zlib = require("node:zlib");
const {
  createDeck, addSlide, addKicker, addTitle, addFooter, addLine, addImageFit, addStatusIcon, writeDeck,
} = require("./deck-kit");

const output = process.argv[2];
if (!output) {
  console.error("usage: node deck-kit/media-example.js <out.pptx>");
  process.exit(2);
}
const deck = createDeck({ author: "Presentation author", title: "Images and status icons", fontFace: "Arial" });
const C = deck.colors;
const FONT = { fontFace: deck.fontFace, margin: 0 };
const rgb = token => [0, 2, 4].map(i => parseInt(token.slice(i, i + 2), 16));

function png(width, height, pixel) {
  const row = width * 3 + 1;
  const raw = Buffer.alloc(row * height); // filter byte 0 (none) opens every row
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) raw.set(pixel(x, y), y * row + 1 + x * 3);
  const chunk = (type, body) => {
    const typed = Buffer.concat([Buffer.from(type, "latin1"), body]);
    const out = Buffer.alloc(typed.length + 8);
    out.writeUInt32BE(body.length, 0);
    typed.copy(out, 4);
    out.writeUInt32BE(zlib.crc32(typed), typed.length + 4);
    return out;
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 2, 0, 0, 0], 8); // 8-bit RGB, no interlace
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header), chunk("IDAT", zlib.deflateSync(raw)), chunk("IEND", Buffer.alloc(0))]);
}

function testPattern(width, height) {
  const [ground, grid, ring, edge] = [C.surface, C.gridline, C.textPrimary, C.borderStrong].map(rgb);
  const [tl, tr, bl, br] = [C.dataPrimary, C.dataSecondary, C.dataTertiary, C.dataQuaternary].map(rgb);
  const unit = Math.min(width, height), cell = unit / 8, mark = unit / 7, line = unit / 300;
  const cx = width / 2, cy = height / 2;
  const onGrid = (v, c) => Math.abs(Math.round((v - c) / cell) * cell - (v - c)) < line;
  const bytes = png(width, height, (x, y) => {
    if (x < line * 2 || y < line * 2 || x >= width - line * 2 || y >= height - line * 2) return edge;
    if (x < mark && y < mark) return tl;
    if (x >= width - mark && y < mark) return tr;
    if (x < mark && y >= height - mark) return bl;
    if (x >= width - mark && y >= height - mark) return br;
    if (Math.abs(Math.hypot(x - cx, y - cy) - unit * 0.35) < line * 2) return ring;
    return onGrid(x, cx) || onGrid(y, cy) ? grid : ground;
  });
  return { data: `image/png;base64,${bytes.toString("base64")}`, srcW: width, srcH: height };
}

const sourceLine = img => `Source: ${img.srcW}×${img.srcH} px test pattern generated by media-example.js`;

function framedImage(slide, name, img, box, mode, caption, altText) {
  slide.addShape(deck.pptx.ShapeType.rect, {
    ...box, fill: { color: C.surfaceElevated }, line: { color: C.border, width: 0.75 }, objectName: `box:${name}`,
  });
  const fit = addImageFit(deck, slide, { ...img, ...box, mode, name, altText });
  const below = box.y + box.h + 0.12;
  slide.addText(caption(fit), { ...FONT, x: box.x, y: below, w: box.w, h: 1.0, fontSize: 14, color: C.textPrimary, valign: "top" });
  slide.addText(sourceLine(img), { ...FONT, x: box.x, y: below + 1.05, w: box.w, h: 0.4, fontSize: 10, color: C.textSecondary, valign: "top" });
}

const contained = img => () => `Contained, uncropped — ${img.srcW}×${img.srcH} px source`;
const landscape = testPattern(1600, 900);
{
  const slide = addSlide(deck);
  addKicker(deck, slide, "Images");
  addTitle(deck, slide, "Contained images keep their proportions");
  const sources = { landscape, portrait: testPattern(900, 1600), square: testPattern(800, 800) };
  const w = 3.6, gap = (deck.CW - 3 * w) / 2;
  Object.entries(sources).forEach(([name, img], i) => {
    framedImage(slide, name, img, { x: deck.MX + i * (w + gap), y: 1.95, w, h: 3.0 }, "contain", contained(img),
      `${name} test pattern: corner markers, a ring and a grid, shown whole inside its frame`);
  });
  addFooter(deck, slide, "Every source is a generated test pattern; replace with real, attributed images");
}
{
  const slide = addSlide(deck);
  addKicker(deck, slide, "Images");
  addTitle(deck, slide, "A crop names the region it shows");
  framedImage(slide, "landscape-full", landscape, { x: deck.MX, y: 1.95, w: 6.0, h: 3.375 }, "contain", contained(landscape),
    "Landscape test pattern with corner markers, a ring and a grid, shown whole");
  framedImage(slide, "landscape-zoom", landscape, { x: deck.MX + 6.6, y: 1.95, w: 3.0, h: 3.375 }, "cover", fit => {
    const [x0, y0] = [Math.round(fit.crop.l * landscape.srcW), Math.round(fit.crop.t * landscape.srcH)];
    const [x1, y1] = [landscape.srcW - Math.round(fit.crop.r * landscape.srcW), landscape.srcH - Math.round(fit.crop.b * landscape.srcH)];
    return `Zoom: centre ${x1 - x0}×${y1 - y0} px of the ${landscape.srcW}×${landscape.srcH} px source `
      + `(x ${x0}–${x1}, y ${y0}–${y1}), cropped, not stretched`;
  }, "Centre crop of the landscape test pattern, zoomed without stretching");
  addFooter(deck, slide, "Left: whole source, contained. Right: the same source, cropped to its centre");
}

const CANDIDATES = ["Candidate A", "Candidate B", "Candidate C", "Candidate D"];
const STATUS = { P: "pass", F: "fail", U: "unknown" };
const ROWS = [ // [capability, one status letter per candidate, { candidate index: footnote key }]
  ["Single sign-on", "PPFP"],
  ["Audit log export", "PUPF"],
  ["Role-based access control", "PPPU"],
  ["Customer-managed encryption keys", "FPUP", { 2: "a" }],
  ["Offline mode", "FFPU"],
  ["Documented API rate limits", "PPUP"],
  ["Bulk import from spreadsheets", "PFPP"],
  ["Exports keep the original row order, column names and number formats in every supported locale", "UPFP", { 1: "b" }],
  ["Webhooks for status changes", "PPFF"],
  ["Accessibility conformance statement", "UFPP"],
  ["Self-hosted deployment", "UPFU", { 0: "a" }],
  ["Two-factor authentication", "PPPP"],
];
const NOTES = [
  ["a", "Claimed in vendor documentation; not exercised in this review."],
  ["b", "Holds for CSV export only; spreadsheet export was not checked."],
];
const LEGEND = [["pass", "Pass: confirmed"], ["fail", "Fail: not supported"], ["unknown", "Unknown: not verified"]];

// Bands are reserved bottom-up, so rows can only grow into the space left above the legend.
const ICON = 0.32, LABEL_W = 4.4, COL_W = (deck.CW - LABEL_W) / CANDIDATES.length;
const NOTE_LINE = 0.22, LEGEND_H = 0.4, GAP = 0.1, HEADER_Y = 1.6, HEADER_H = 0.4;
const NOTES_Y = deck.FOOTER_Y - GAP - NOTES.length * NOTE_LINE;
const LEGEND_Y = NOTES_Y - GAP - LEGEND_H;
const ROWS_Y = HEADER_Y + HEADER_H, ROWS_H = LEGEND_Y - GAP - ROWS_Y;
// ponytail: wrap estimated from a conservative 14pt average glyph width; the render confirms it.
const CHARS_PER_LINE = Math.floor((LABEL_W - 0.2) / ((14 / 72) * 0.55));
const rowHeight = label => Math.ceil(label.length / CHARS_PER_LINE) * 0.25 + 0.2;

const pages = [[]];
let used = 0;
for (const row of ROWS) {
  const h = rowHeight(row[0]);
  if (h > ROWS_H) throw new Error(`Row cannot fit on any slide at 14pt: ${row[0]}`);
  if (used + h > ROWS_H) { pages.push([]); used = 0; }
  pages[pages.length - 1].push(row);
  used += h;
}

let first = 1;
pages.forEach((rows, page) => {
  const slide = addSlide(deck);
  addKicker(deck, slide, "Status icons");
  addTitle(deck, slide, `Capability check by candidate${page ? " (continued)" : ""}`, { h: 0.55 });
  CANDIDATES.forEach((name, c) => slide.addText(name, {
    ...FONT, x: deck.MX + LABEL_W + c * COL_W, y: HEADER_Y, w: COL_W, h: HEADER_H,
    fontSize: 14, bold: true, color: C.textPrimary, align: "center", valign: "middle",
  }));
  let y = ROWS_Y;
  addLine(deck, slide, deck.MX, y, deck.MX + deck.CW, y, { line: { color: C.borderStrong, width: 1 } });
  rows.forEach(([label, statuses, notes = {}], r) => {
    const h = rowHeight(label);
    slide.addText(label, {
      ...FONT, x: deck.MX, y, w: LABEL_W - 0.2, h, fontSize: 14, color: C.textPrimary, valign: "middle",
      objectName: `row:${first + r}`,
    });
    [...statuses].forEach((s, c) => {
      const x = deck.MX + LABEL_W + c * COL_W + (COL_W - ICON) / 2, iy = y + (h - ICON) / 2;
      addStatusIcon(deck, slide, STATUS[s], { x, y: iy, size: ICON });
      if (notes[c]) slide.addText(notes[c], { ...FONT, x: x + ICON + 0.04, y: iy - 0.06, w: 0.2, h: 0.2, fontSize: 10, color: C.textSecondary });
    });
    y += h;
    addLine(deck, slide, deck.MX, y, deck.MX + deck.CW, y, { line: { color: C.gridline, width: 0.75 } });
  });
  LEGEND.forEach(([status, words], i) => {
    const x = deck.MX + i * 3.4;
    addStatusIcon(deck, slide, status, { x, y: LEGEND_Y + (LEGEND_H - ICON) / 2, size: ICON });
    slide.addText(words, {
      ...FONT, x: x + ICON + 0.12, y: LEGEND_Y, w: 3.0, h: LEGEND_H, fontSize: 14, color: C.textPrimary,
      valign: "middle", objectName: `legend:${status}`,
    });
  });
  const used = new Set(rows.flatMap(([, , notes = {}]) => Object.values(notes)));
  const notes = NOTES.filter(([key]) => used.has(key));
  slide.addText(notes.map(([key, text], i) => ({ text: `${key}   ${text}`, options: { breakLine: i < notes.length - 1 } })), {
    ...FONT, x: deck.MX, y: NOTES_Y, w: deck.CW, h: NOTES.length * NOTE_LINE, fontSize: 10, color: C.textSecondary,
    valign: "top", objectName: "footnotes",
  });
  addFooter(deck, slide, "Source: illustrative statuses for layout only", `Rows ${first}–${first + rows.length - 1} of ${ROWS.length}`);
  first += rows.length;
});

writeDeck(deck.pptx, output).then(console.log).catch(error => { console.error(error.message); process.exitCode = 1; });
